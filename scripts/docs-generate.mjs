function main() {
  const check = process.argv.includes("--check");
  const rendered = [];
  for (const [file, make] of OUTPUTS) {
    const text = make().replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
    rendered.push([file, text]);
    const page = pages.get(urlOfPage(contentDir, join(root, file)));
    if (page) page.front = splitFrontmatter(text).front;
  }
  if (problems.length) {
    console.error(`docs-generate problems:\n${[...new Set(problems)].map((p) => `  ${p}`).join("\n")}`);
    process.exit(1);
  }
  const stale = [];
  for (const [file, text] of rendered) {
    const path = join(root, file);
    if (check) {
      if (!existsSync(path) || readFileSync(path, "utf8").replace(/\r\n/g, "\n") !== text) stale.push(`${file} is stale; run node scripts/docs-generate.mjs`);
    } else writeFileSync(path, text);
  }
  if (stale.length) {
    console.error(stale.join("\n"));
    process.exit(1);
  }
  console.log(`docs-generate: ${check ? "up to date" : "wrote"} ${rendered.length} pages`);
}

