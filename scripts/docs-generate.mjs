// ---------------------------------------------------------------- props and events
function splitRow(line) {
  const cells = [];
  let cur = "";
  let tick = false;
  const inner = line.trim().replace(/^\|/, "").replace(/\|$/, "");
  for (let i = 0; i < inner.length; i++) {
    const c = inner[i];
    if (c === "`") tick = !tick;
    if (c === "\\" && inner[i + 1] === "|") {
      cur += "|";
      i++;
    } else if (c === "|" && !tick) {
      cells.push(cur.trim());
      cur = "";
    } else cur += c;
  }
  cells.push(cur.trim());
  return cells;
}

const REFERENCE_PAGES = /^\/docs\/(components-props|events-state|contracts|plugins|types-hooks)/;
const PAGE_RANK = (url) => (/events-state/.test(url) ? 0 : /components-props/.test(url) ? 1 : 2);

/** name -> list of { url, anchor, desc } for table rows whose first cell is one backticked name. */
function tableIndex() {
  const index = new Map();
  const urls = [...pages.keys()].filter((u) => REFERENCE_PAGES.test(u)).sort((a, b) => PAGE_RANK(a) - PAGE_RANK(b));
  for (const url of urls) {
    const lines = pages.get(url).body.split("\n");
    let anchor = "";
    let head = [];
    let fence = false;
    for (const [i, line] of lines.entries()) {
      if (/^\s*```/.test(line)) fence = !fence;
      if (fence) continue;
      const h = /^#{2,4}\s+(.*)$/.exec(line);
      if (h) {
        const explicit = /\[#([^\]]+)\]\s*$/.exec(h[1]);
        const slug = h[1].replace(/`/g, "").toLowerCase().replace(/[^\p{L}\p{N}\s_-]/gu, "").trim().replace(/\s/g, "-");
        anchor = explicit ? explicit[1] : pages.get(url).anchors.has(slug) ? slug : "";
      }
      if (!line.startsWith("|") || /^\|\s*-/.test(line)) continue;
      const cells = splitRow(line);
      if (/^\|\s*-/.test(lines[i + 1] ?? "")) {
        head = cells.map((c) => c.toLowerCase());
        continue;
      }
      const m = /^`([A-Za-z_$][\w$]*)`$/.exec(cells[0]);
      if (!m) continue;
      const di = head.findIndex((c) => /^(description|purpose|meaning|fires when|cause|effect)/.test(c));
      const desc = di > 0 ? cells[di] : head.length === 2 ? cells[1] : "";
      index.set(m[1], [...(index.get(m[1]) ?? []), { url, anchor, desc: desc ?? "" }]);
    }
  }
  return index;
}

function jsdocOf(file, name) {
  const text = read(file);
  const m = new RegExp(`/\\*\\*((?:(?!\\*/)[\\s\\S])*?)\\*/\\s*(?:readonly\\s+)?${name}\\??\\s*[:(]`).exec(text);
  if (!m) return "";
  return sentence(m[1].replace(/^\s*\*\s?/gm, "").replace(/\{@link\s+([^}\s]+)[^}]*\}/g, "$1"));
}

function members(file, typeName) {
  const def = parseTypes(read(file)).find((d) => d.name === typeName);
  if (!def) {
    problems.push(`props: ${typeName} not found in ${file}`);
    return [];
  }
  return [...def.members.keys()];
}

