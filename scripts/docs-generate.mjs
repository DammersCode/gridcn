const parity = JSON.parse(read("research/parity-matrix.json"));
const CLIENT = ["L", "PC"];
const SERVER = ["PS", "Z", "SS", "FS"];
function modeText(row, ids) {
  const statuses = ids.map((id) => row.cells[id].status).filter((s) => s !== "n/a");
  if (statuses.length === 0) return "n/a";
  if (statuses.every((s) => s === "supported")) return "Yes";
  if (statuses.every((s) => s === "gap")) return "Gap";
  if (statuses.some((s) => s === "gap")) return "Partial";
  return "Not verified";
}

const FIRST_TAGGED_RELEASE = "1.0.0";

// CHANGELOG.md lists releases newest first, so a higher index is an older release.
function changelogReleases() {
  const parts = read("CHANGELOG.md").split(/^## (\S+).*$/m);
  const releases = [];
  for (let i = 1; i < parts.length; i += 2) releases.push({ name: parts[i], body: parts[i + 1] });
  const firstNamed = new Map();
  for (const [index, { body }] of [...releases.entries()].reverse()) {
    for (const m of body.matchAll(/`([A-Za-z_$][\w$]*)/g)) if (!firstNamed.has(m[1])) firstNamed.set(m[1], index);
  }
  return { order: releases.map((r) => r.name), firstNamed };
}

/** Fails a row whose title names a symbol that CHANGELOG.md first names in a release after the row's Since. */
function checkSinceAgainstChangelog(row, release, { order, firstNamed }) {
  const symbols = new Set([...row.feature.matchAll(/`([A-Za-z_$][\w$]*)`|\b(use[A-Z]\w*|DataGrid[A-Z]\w*)\b/g)].map((m) => m[1] ?? m[2]));
  const sinceIndex = order.indexOf(release);
  for (const symbol of symbols) {
    const named = firstNamed.get(symbol);
    if (named !== undefined && sinceIndex !== -1 && named < sinceIndex) {
      problems.push(`feature matrix: ${row.id} says Since ${release}, but its title names ${symbol}, which CHANGELOG.md first names under ${order[named]}; split the row or list it in FEATURE_SINCE`);
    }
  }
}

function sinceOf() {
  const releases = new Set(changelogReleases().order);
  const since = new Map();
  for (const [release, ids] of Object.entries(FEATURE_SINCE)) {
    if (!releases.has(release)) problems.push(`feature matrix: FEATURE_SINCE names ${release}, which is no CHANGELOG.md heading`);
    for (const id of ids) {
      if (!parity.features.some((f) => f.id === id)) problems.push(`feature matrix: FEATURE_SINCE lists unknown feature ${id}`);
      since.set(id, release);
    }
  }
  return since;
}

function featureMatrix() {
  const rows = [];
  const since = sinceOf();
  const changelog = changelogReleases();
  for (const row of parity.features) {
    const f = FEATURES[row.id];
    if (!f) {
      problems.push(`feature matrix: parity feature ${row.id} has no mapping`);
      continue;
    }
    if (f.item && !itemsByName.has(f.item)) problems.push(`feature matrix: unknown item ${f.item}`);
    const statuses = Object.values(row.cells).map((c) => c.status).filter((s) => s !== "n/a");
    const notBuilt = !f.item && statuses.length > 0 && statuses.every((s) => s === "gap");
    const kind = f.item ? "Add-on" : notBuilt ? "Not built" : "Core";
    const item = f.item ? code(f.item) : notBuilt ? "none" : code("data-grid");
    const release = notBuilt ? "none" : (since.get(row.id) ?? FIRST_TAGGED_RELEASE);
    if (!notBuilt) checkSinceAgainstChangelog(row, release, changelog);
    rows.push([cell(row.feature), kind, item, modeText(row, CLIENT), modeText(row, SERVER), release, link(f.guide[0], f.guide[1]), link(f.reference[0], f.reference[1])]);
  }
  return [
    frontmatter({ title: "Feature matrix", description: "See which features are core or add-on, whether each works with client and server data, and where its guide is.", type: "cheatsheet", icon: "Table", aliases: ["row grouping", "group rows", "tree data", "aggregation", "since version"] }),
    MARKER,
    "",
    "Core features ship in `data-grid`. An add-on feature needs the item in the Item column. Client covers a local array and client pagination. Server covers server pages, scroll mode, server sort, and server filter. A Gap cell is a known gap. A Partial cell has a gap in some of its modes. The [data mode support](/docs/data-modes/data-mode-support) page names each gap.",
    "",
    `Since names the first release with the feature. ${FIRST_TAGGED_RELEASE} is the first tagged release. Item names the item that holds the feature. In 1.x, \`data-grid-lazy\` held scroll row fetching. Unreleased marks a feature that only an install without a ref has. The [changelog](https://github.com/DammersCode/gridcn/blob/main/CHANGELOG.md) lists each release.`,
    "",
    table(["Feature", "Kind", "Item", "Client", "Server", "Since", "Guide", "Reference"], rows),
    related(["/docs/data-modes/data-mode-support", "every feature against every data mode"], ["/docs/fit-features/add-ons-a-z", "every add-on"], ["/docs/data-modes", "choose where the rows come from"]),
  ].join("\n");
}

