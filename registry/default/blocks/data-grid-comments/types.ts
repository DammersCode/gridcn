import type { DataChange, DataGridPlugin } from "@/registry/default/blocks/data-grid/data-grid";
import type { DataGridCommentsLabels } from "./labels";

/** Who wrote or resolved a comment. A per-record snapshot: the identity is `id`, and a later rename changes only new writes. */
export type CommentAuthor = {
  /** 1..128 characters, no control characters. */
  id: string;
  /** Display name, at most 80 characters; control and bidi-override characters are stripped. */
  name?: string;
  /** CSS color of the author chip, at most 64 characters; an invalid color falls back to a theme token. */
  color?: string;
};

/** One comment on one cell. The cell is addressed by `rowId` and `columnId`, never by a view index. */
export type CellComment = {
  /** Client-generated key (`createId`); the permanent identity and the create idempotency key. */
  id: string;
  rowId: string;
  columnId: string;
  /** 1..`maxTextLength` characters after trim. */
  text: string;
  /** Absent for an anonymous comment. A server may add it once; it never changes or goes away after that. */
  author?: CommentAuthor;
  /** Epoch milliseconds. */
  createdAt: number;
  /** Epoch milliseconds; the server should stamp it. */
  updatedAt: number;
  /** Integer 1..1,000,000,000; +1 per accepted write (a stamping server may return a higher one). */
  version: number;
  /** Id of the write that produced this version; generated by the add-on. */
  writeId?: string;
  resolved: boolean;
  resolvedBy?: CommentAuthor;
  resolvedAt?: number;
};

/** One write as a transport sees it. Resolve and reopen are `upsert` with `resolved` changed. A delete is a tombstone. */
export type CommentChange =
  | { kind: "upsert"; comment: CellComment; baseVersion?: number }
  | { kind: "delete"; id: string; rowId: string; columnId: string; version: number; writeId?: string; baseVersion?: number };

/** What made a store write: an acknowledgement, a remote batch, a fetch answer, a row id swap, or `removeComments`. */
export type CommentSource = "ack" | "remote" | "fetch" | "id-swap" | "remove";

/** What a comment write does. */
export type CommentAction = "create" | "update" | "delete" | "resolve" | "reopen";

/** Context of `onCommentsChange`. */
export type CommentsChangeCtx = { changes: readonly CommentChange[]; source: CommentSource };

/** Context of `onCommentSave`. */
export type CommentSaveCtx = {
  action: CommentAction;
  /** Carries `baseVersion`, `writeId`, and the new record. */
  change: CommentChange;
  /** The last confirmed record before the write. */
  prev?: CellComment;
};

/** Reasons a transport may reject a write with. */
export type CommentSaveRejectReason = "stale" | "forbidden" | "invalid" | "limit";

/** What `onCommentSave` may answer. */
export type CommentSaveAck =
  | { comment?: CellComment | null }
  | { rejected: { reason: CommentSaveRejectReason; message?: string; current?: CellComment | null } };

/** Return type of `onCommentSave`: `void` accepts the write exactly as sent. */
export type CommentSaveResult = void | CommentSaveAck | Promise<void | CommentSaveAck>;

/** Every reason a write is refused or reverted. */
export type CommentRejectReason = CommentSaveRejectReason | "read-only" | "row-busy" | "error";

/** Context of `onCommentRejected`. */
export type CommentRejectedCtx = {
  action: CommentAction;
  /** Absent when the write was refused before a record existed (invalid `createId` or `currentUser`). */
  change?: CommentChange;
  reason: CommentRejectReason;
  message?: string;
  current?: CellComment | null;
  error?: unknown;
};

/** Context of the `canEdit`, `canDelete`, and `canResolve` gates. `action` tells resolve from reopen. `user` is absent without `currentUser`. `signal` aborts on unmount or when the request is superseded. */
export type CommentGateCtx = { comment: CellComment; action: CommentAction; user?: CommentAuthor; signal: AbortSignal };

/** Context of the `canCreate` gate. `user` is absent without `currentUser`. */
export type CommentCreateGateCtx = { rowId: string; columnId: string; user?: CommentAuthor; signal: AbortSignal };

/** Context of `fetchComments`. */
export type CommentFetchCtx = { rowIds: readonly string[]; signal: AbortSignal };

/** Context of `onFetchError`. */
export type CommentFetchErrorCtx = { reason: "error" | "limit"; rowIds: readonly string[]; error?: unknown };

/** Context of `onOrphanedComments`: comments whose rows were deleted. They stay in the store. */
export type OrphanedCommentsCtx = { comments: readonly CellComment[]; rowIds: readonly string[]; source: DataChange<unknown>["source"] };

/** Why `applyRemote` skipped a change. */
export type ApplyRemoteSkipReason = "stale" | "duplicate" | "invalid" | "limit" | "tombstoned" | "unknown";

/** What `applyRemote` did with a batch. */
export type ApplyRemoteVerdict = {
  applied: number;
  skippedCount: number;
  /** The first 100 skipped changes. */
  skipped: readonly { index: number; reason: ApplyRemoteSkipReason }[];
  /** Changes beyond the batch limit, ignored. */
  truncated: number;
};

/** The context-menu item shape the add-on contributes. */
export type CommentMenuItem = {
  id: string;
  label: string;
  onClick: () => void;
};

/** Structurally compatible with the context-menu add-on's `CellMenuItemsResolver`; pass it as `getCellMenuItems`. */
export type CommentMenuItemsResolver = <TItem extends { id: string }>(
  ctx: { rowId: string; columnId: string; viewRowIndex: number },
  defaults: TItem[],
) => (TItem | CommentMenuItem)[];

/** Options of {@link useDataGridComments}. */
export type UseDataGridCommentsOptions = {
  /** The user who writes. Without it, writes are anonymous. Only `id` is required. A present but invalid value refuses every write. */
  currentUser?: CommentAuthor;
  /** Blocks every comment write and hides the composer and the actions. Default `false`. */
  readOnly?: boolean;
  /** Shows resolve and reopen. `false` ignores the `resolved` state in the UI and refuses resolve and reopen. Default `true`. */
  enableResolve?: boolean;
  /** Shows edit. `false` removes the Edit action and refuses edits with the reason `"forbidden"`. Default `true`. */
  enableEdit?: boolean;
  /** Shows delete. `false` removes the Delete action and refuses deletes with the reason `"forbidden"`. Default `true`. */
  enableDelete?: boolean;
  /** Controlled confirmed comments. Keep the reference stable between renders. */
  comments?: readonly CellComment[];
  /** One-shot seed. */
  defaultComments?: readonly CellComment[];
  /** State channel: one call per store write, `next` holds confirmed records only. With `fetchComments` it is a partial cache: save from `ctx.changes`. */
  onCommentsChange?: (next: readonly CellComment[], ctx: CommentsChangeCtx) => void;
  /** Saves one write. Return nothing to accept it as sent, `{ comment }` for the authoritative record, `{ rejected }` or throw to revert. */
  onCommentSave?: (ctx: CommentSaveCtx) => CommentSaveResult;
  /** Called once per refused or reverted write. */
  onCommentRejected?: (ctx: CommentRejectedCtx) => void;
  /** Broadcast seam: fires once per confirmed local write. It cannot refuse. */
  onLocalChange?: (change: CommentChange) => void;
  /** Gate for creating a comment. Default: anyone. */
  canCreate?: (ctx: CommentCreateGateCtx) => boolean | Promise<boolean>;
  /** Gate for editing. Default: the author, or anyone when the comment has no author. */
  canEdit?: (ctx: CommentGateCtx) => boolean | Promise<boolean>;
  /** Gate for deleting. Default: the author, or anyone when the comment has no author. */
  canDelete?: (ctx: CommentGateCtx) => boolean | Promise<boolean>;
  /** Gate for resolving and reopening; `ctx.action` tells them apart. Default: anyone. */
  canResolve?: (ctx: CommentGateCtx) => boolean | Promise<boolean>;
  /** Loads the comments of the rendered rows. */
  fetchComments?: (ctx: CommentFetchCtx) => Promise<readonly CellComment[]>;
  /** Called for a failed fetch request or for records dropped for a bound. */
  onFetchError?: (ctx: CommentFetchErrorCtx) => void;
  /** Called when rows with comments are deleted. */
  onOrphanedComments?: (ctx: OrphanedCommentsCtx) => void;
  /** Default: `crypto.randomUUID` with a fallback outside secure contexts. */
  createId?: () => string;
  /** Applied to local text before the bounds are checked. */
  normalizeText?: (text: string) => string;
  /** Default 2,000; ceiling 20,000. */
  maxTextLength?: number;
  /** Default 50; ceiling 500. */
  maxCommentsPerCell?: number;
  /** Default 50,000; ceiling 500,000. */
  maxComments?: number;
  /** Uncontrolled fetch cache bound in rows. Default 2,000; ceiling 20,000. */
  maxCachedRows?: number;
  /** Let comment writes through on a `readOnly` grid. Default `false`. */
  allowWhenReadOnly?: boolean;
  /** Hide the markers of resolved-only cells. Default `false`. */
  hideResolved?: boolean;
  /** Overrides the strings of the comments UI. A key set to `undefined` keeps its default. */
  labels?: Partial<DataGridCommentsLabels>;
  /** Class of the popover root, merged with `cn`. */
  className?: string;
};

/** Return value of {@link useDataGridComments}. */
export type UseDataGridCommentsResult = {
  /** One entry of the grid's `plugins`. Stable for the component's lifetime. */
  plugin: DataGridPlugin;
  /** Applies records another client wrote. Works in controlled and uncontrolled mode. */
  applyRemote(changes: readonly CommentChange[]): ApplyRemoteVerdict;
  /** A bounded snapshot, not reactive. Partial under the fetch cache. */
  getComments(): readonly CellComment[];
  /** Forgets the comments of these rows (emits `onCommentsChange` with source `"remove"`). Returns how many were removed. */
  removeComments(target: { rowIds: readonly string[] }): number;
  /** Marks rows unfetched and loads them again. */
  refetchComments(target?: { rowIds?: readonly string[] }): void;
  /** Opens the popover for a cell. `false` for a hole, a filtered-out row, or a hidden column. */
  openComments(ref: { rowId: string; columnId: string }): boolean;
  closeComments(): void;
  /** Pass as the context menu's `getCellMenuItems` to add a "Comments…" item. */
  getCommentMenuItems: CommentMenuItemsResolver;
};
