import Database from "better-sqlite3";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { PGlite } from "@electric-sql/pglite";
import { PGLiteSocketServer } from "@electric-sql/pglite-socket";
import { PrismaBetterSqlite3 } from "@prisma/adapter-better-sqlite3";
import { PrismaPg } from "@prisma/adapter-pg";
import type { ColumnSpec } from "@/registry/default/blocks/data-grid-server-query/data-grid-server-query";
import { type PrismaModelDelegate, createPrismaGridQuery, definePrismaColumnMap } from "@/registry/default/blocks/data-grid-server-query-prisma/data-grid-server-query-prisma";
import { type Harness, seedPg, seedSqlite } from "../engines";
import { type Engine, fixtureSpecs, groupSpecs } from "../fixture";

type Row = Record<string, unknown>;

/** A model delegate of the generated client, typed by the shape the tests call. */
export type Delegate = PrismaModelDelegate & {
  findMany(args?: Row): Promise<Row[]>;
  count(args?: Row): Promise<number>;
  createMany(args: { data: Row[] }): Promise<{ count: number }>;
  updateMany(args: { where: unknown; data: Row }): Promise<{ count: number }>;
  deleteMany(args: { where: unknown }): Promise<{ count: number }>;
};
type Client = {
  item: Delegate;
  cursorItem: Delegate;
  kind: Delegate;
  $on(event: "query", listener: (event: { query: string }) => void): void;
  $disconnect(): Promise<void>;
};
type Generated = { PrismaClient: new (options: Row) => Client; Prisma: Record<string, Readonly<Record<string, string>>> };

export const PROVIDER = { sqlite: "sqlite", pg: "postgresql" } as const;
const here = dirname(fileURLToPath(import.meta.url));

/** A client of the schema in this folder, generated by `generate.ts`; a computed specifier keeps the type checks off the generated files. */
async function generated(engine: Engine): Promise<Generated> {
  const url = pathToFileURL(join(here, "generated", PROVIDER[engine], "client.ts")).href;
  return (await import(/* @vite-ignore */ url)) as Generated;
}

export type PrismaDatabase = {
  client: Client;
  Prisma: Generated["Prisma"];
  /** The SQL text of every statement the client sent, in order. */
  statements: string[];
  close(): Promise<void>;
};

/** A Prisma client over a SQLite file, or over an in-process PGlite through a socket on an OS-assigned port. */
export async function connectPrisma(target: { file: string } | { pglite: PGlite }): Promise<PrismaDatabase> {
  const engine: Engine = "file" in target ? "sqlite" : "pg";
  const { PrismaClient, Prisma } = await generated(engine);
  let server: PGLiteSocketServer | undefined;
  let adapter: unknown;
  if ("file" in target) adapter = new PrismaBetterSqlite3({ url: `file:${target.file}` });
  else {
    server = new PGLiteSocketServer({ db: target.pglite, port: 0, host: "127.0.0.1" });
    await server.start();
    adapter = new PrismaPg({ connectionString: `postgresql://postgres@${server.getServerConn()}/postgres`, max: 1 });
  }
  const client = new PrismaClient({ adapter, log: [{ emit: "event", level: "query" }] });
  const statements: string[] = [];
  client.$on("query", (event) => statements.push(event.query));
  return {
    client,
    Prisma,
    statements,
    close: async () => {
      await client.$disconnect();
      await server?.stop();
    },
  };
}

/** A SQLite file in its own temporary folder; the Prisma adapter opens its own connection, so `:memory:` would not be shared. */
export function sqliteFile(): { database: Database.Database; file: string; remove(): void } {
  const folder = mkdtempSync(join(tmpdir(), "gridcn-prisma-"));
  const file = join(folder, "test.db");
  const database = new Database(file);
  return {
    database,
    file,
    remove: () => {
      database.close();
      rmSync(folder, { recursive: true, force: true });
    },
  };
}

/** The Prisma map of `specs`, whose fields all have `?` in the schema apart from the key and the tenant column. */
export function prismaColumns(fields: Readonly<Record<string, string>>, specs: Record<string, ColumnSpec>, notNull: readonly string[] = ["id", "tenantId"]) {
  const nullable: Record<string, ColumnSpec & { nullable: boolean }> = Object.fromEntries(Object.entries(specs).map(([id, spec]) => [id, { ...spec, nullable: !notNull.includes(spec.field ?? id) }]));
  return definePrismaColumnMap<object>()(fields, nullable);
}

/** The Prisma harness of the shared fixture, on its own database seeded like the Drizzle and Kysely one. */
export async function openPrisma(engine: Engine): Promise<{ harness: Harness; db: PrismaDatabase; close(): Promise<void> }> {
  let db: PrismaDatabase;
  let release: () => Promise<void> | void;
  if (engine === "sqlite") {
    const sqlite = sqliteFile();
    seedSqlite(sqlite.database);
    db = await connectPrisma({ file: sqlite.file });
    release = sqlite.remove;
  } else {
    const pglite = new PGlite();
    await seedPg(pglite);
    db = await connectPrisma({ pglite });
    release = () => pglite.close();
  }
  const fields = db.Prisma["ItemScalarFieldEnum"]!;
  const model = db.client.item;
  const harness: Harness = {
    engine,
    adapter: "prisma",
    // An import route converts the parsed text itself: `parseImportRows` keeps integers as text and has no `nativeValue`.
    insert: async (rows) => {
      const data = rows.map((row) => ({
        ...row,
        id: BigInt(row["id"] as number),
        ...(typeof row["qty"] === "string" ? { qty: Number(row["qty"]) } : {}),
        ...(engine === "pg" && typeof row["createdAt"] === "string" ? { createdAt: new Date(row["createdAt"]) } : {}),
      }));
      await model.createMany({ data });
    },
    remove: async (ids) => {
      await model.deleteMany({ where: { id: { in: ids.map(BigInt) } } });
    },
    make: (options = {}) => {
      const specs = options.groups ? groupSpecs(engine) : fixtureSpecs(engine, options.searchable === false ? "none" : "default");
      return createPrismaGridQuery<Row, { tenantId: number }>({
        model,
        provider: PROVIDER[engine],
        columns: prismaColumns(fields, specs),
        rowScope: options.rowScope ? (context) => ({ tenantId: context.tenantId }) : undefined,
        rowCount: options.rowCount,
        timeZone: options.timeZone,
      }) as never;
    },
  };
  return {
    harness,
    db,
    close: async () => {
      await db.close();
      await release();
    },
  };
}
